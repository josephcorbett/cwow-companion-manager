local new = dofile("tests/wow_mock.lua")
local cases, assertions = 0, 0
local function check(value, message)
    assertions = assertions + 1
    assert(value, message or "check failed")
end
local function equal(actual, expected)
    check(actual == expected, "expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local function contains(actual, expected) check(actual:find(expected, 1, true), actual .. " lacks " .. expected) end
local function test(name, fn)
    local ok, err = pcall(fn)
    if not ok then error(name .. ": " .. tostring(err), 0) end
    cases = cases + 1
    print("ok - " .. name)
end
local function ready()
    local w = new(); w.load(); return w, w.C.Manager, w.C.Transport, w.C.Party
end
local function recruit(w, m, baseline)
    m.Recruit("priest")
    equal(w.lastCommand(), "playerbots bot list")
    w.roster(baseline)
    equal(w.lastCommand(), "playerbots bot addclass priest")
end
local function dismiss(w, m)
